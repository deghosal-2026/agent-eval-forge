"""Per-agent wrapper cookie-cutter template.

Generates wrapper Python files that expose ``build_agent(payload, model)``
and call repo-specific builders, plus matching field-test config JSON.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, ClassVar


class AgentWrapperTemplate:
    """Generates per-agent wrapper code and field config.

    Produces two files for a new agent:

    - A Python wrapper module with ``build_agent()`` and ``run()`` functions.
    - A JSON config file for the EvalForge field test harness.

    Usage::

        wrapper_code = AgentWrapperTemplate.render("my_agent", "...", "..." )
        config_json = AgentWrapperTemplate.render_config("my_agent", "...", ...)
        AgentWrapperTemplate.save("my_agent", "/output", wrapper_code, config_json)
    """

    WRAPPER_TEMPLATE = '''"""Auto-generated agent wrapper for {agent_name}.

Source repo: {repo_url}
Generated by evalforge.templates.AgentWrapperTemplate
"""

from __future__ import annotations

from typing import Any, ClassVar

from {module} import {builder_function}


def build_agent(payload: dict[str, Any], model: str | None = None) -> Any:
    """Build agent from scenario payload.

    Args:
        payload: EvalForge invocation payload (scenario_id, input, tools, ...).
        model: Optional model override (e.g. "gpt-4o-mini").

    Returns:
        A compiled graph / agent instance ready for .invoke().
    """
    return {builder_function}(payload, model)


def run(payload: dict[str, Any]) -> dict[str, Any]:
    """EvalForge-compatible run function (for PythonImportAdapter)."""
    agent = build_agent(payload, payload.get("model"))
    config = {{"configurable": {{"thread_id": payload.get("run_id", "default")}}}}
    result = agent.invoke(payload["input"], config)
    if isinstance(result, dict):
        return result
    return {{"output": {{"final": str(result)}}}}
'''

    CONFIG_TEMPLATE: ClassVar[dict[str, Any]] = {
        "agent_id": "{agent_name}",
        "adapter_type": "{adapter_type}",
        "adapter_config": {
            "module": "agents.{agent_name}",
            "function": "build_agent",
        },
        "setup_commands": [],
        "scenario_packs": [],
        "acceptance": {"min_pass_rate": 0.8},
        "tags": [],
        "quarantined": False,
    }

    @staticmethod
    def render(
        agent_name: str,
        repo_url: str,
        builder_function: str,
        adapter_type: str = "langgraph",
        tools: list[str] | None = None,
    ) -> str:
        """Render a wrapper Python file for an agent.

        Parses the *builder_function* string (e.g. ``"my_module.build"``)
        into module and function parts.

        Args:
            agent_name: Short name used in the wrapper module.
            repo_url: Source repository URL for attribution.
            builder_function: Fully qualified function name (``"module.fn"``).
            adapter_type: Adapter type (default ``"langgraph"``).
            tools: Not used in the template currently; reserved for future use.

        Returns:
            The rendered wrapper Python source code.
        """
        module_parts = builder_function.rsplit(".", 1)
        if len(module_parts) == 2:
            module, func = module_parts
        else:
            module, func = "agent", builder_function
        return AgentWrapperTemplate.WRAPPER_TEMPLATE.format(
            agent_name=agent_name,
            repo_url=repo_url,
            module=module,
            builder_function=func,
        )

    @staticmethod
    def render_config(
        agent_name: str,
        repo_url: str,
        adapter_type: str,
        setup_commands: list[str],
        scenario_packs: list[str],
    ) -> str:
        """Render a field config JSON string for an agent.

        Args:
            agent_name: Agent identifier.
            repo_url: Source repository URL.
            adapter_type: Adapter type (e.g. ``"langgraph"``, ``"pydantic_ai"``).
            setup_commands: Shell commands to run during agent setup.
            scenario_packs: List of scenario pack paths to run against this agent.

        Returns:
            A JSON string suitable for writing as a field config file.
        """
        config = {
            "agent_id": agent_name,
            "repo_url": repo_url,
            "adapter_type": adapter_type,
            "adapter_config": {
                "module": f"agents.{agent_name}",
                "function": "build_agent",
            },
            "setup_commands": setup_commands,
            "scenario_packs": scenario_packs,
            "acceptance": {"min_pass_rate": 0.8},
            "tags": [],
            "quarantined": False,
        }
        return json.dumps(config, indent=2)

    @staticmethod
    def save(
        agent_name: str,
        output_dir: str,
        wrapper_code: str,
        config_json: str,
    ) -> tuple[Path, Path]:
        """Write the wrapper Python file and config JSON to disk.

        Creates the output directory if it does not exist.

        Args:
            agent_name: Agent identifier (used for file naming).
            output_dir: Target directory for generated files.
            wrapper_code: Python source from :meth:`render`.
            config_json: JSON string from :meth:`render_config`.

        Returns:
            Tuple of ``(wrapper_path, config_path)``.
        """
        out = Path(output_dir)
        out.mkdir(parents=True, exist_ok=True)

        wrapper_path = out / f"{agent_name}.py"
        config_path = out / f"{agent_name}.json"

        wrapper_path.write_text(wrapper_code)
        config_path.write_text(config_json)

        return wrapper_path, config_path

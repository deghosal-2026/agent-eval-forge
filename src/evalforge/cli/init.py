"""``evalforge init`` — scaffold a new EvalForge project.

Creates the directory structure and starter files for running
evaluation scenarios. Two templates are available:

- **minimal** (default): config file + one example scenario pack.
- **full**: adds an agent stub, test file, and fixture scaffolding.
"""

from __future__ import annotations

from pathlib import Path

import click

# Template content for evalforge.toml — the project configuration file.
# All values have sensible defaults; this file is optional.
_TEMPLATE_EVALFORGE_TOML = """\
# EvalForge configuration — customize to your project.
# This file is optional. All values have sensible defaults.

[judge]
# Judge provider and model for LLM-as-judge scoring.
provider = "openai"
model = "gpt-4o-mini"

[output]
# Output directory for run artifacts.
dir = ".evalforge"
log_level = "info"

[scoring]
# Strict mode: treat warnings as failures.
strict = false
# Compare mode: snapshot (compare saved scores) or rescore (re-run judge)
compare_mode = "snapshot"
"""

# Template content for the example scenario pack YAML file
_TEMPLATE_SCENARIO_PACK = """\
# Auto-generated by `evalforge init` — replace with your own scenarios.
pack:
  name: "my-scenarios"
  version: "0.1.0"
  description: "My evaluation scenarios"

scenarios:
  - id: "sc-01-hello"
    title: "Hello world check"
    goal: "Verify the agent returns the correct greeting"
    input: "Say hello and introduce yourself."
    allowed_tools: []
    disallowed_tools: []
    expected:
      type: exact
      value: "hello"
    metrics:
      task_completion:
        threshold: 0.8
      output_correctness:
        threshold: 0.7
    tags: [basic, smoke]
"""

# Template content for a minimal agent Python module
_TEMPLATE_AGENT = """\
\"\"\"My custom agent — replace with your own implementation.

EvalForge calls ``run(input_text: str) -> str`` for each scenario.
Import your own agent, API client, or model here.
\"\"\"

from __future__ import annotations


def run(input_text: str) -> str:
    \"\"\"Process the scenario input and return the agent's response.\"\"\"
    return f"Received: {input_text}"
"""

# Template content for pytest scenario tests
_TEMPLATE_TEST_SCENARIOS = """\
\"\"\"Pytest scenarios for my-scenarios pack.

Run with: pytest tests/
\"\"\"

from __future__ import annotations

import pytest

from evalforge.loading import load_pack


SCENARIO_PACK = "scenarios/my-scenarios.yaml"


@pytest.fixture(scope="module")
def pack():
    return load_pack(SCENARIO_PACK)


def test_pack_loads(pack):
    \"\"\"The scenario pack parses without errors.\"\"\"
    assert pack.pack.name == "my-scenarios"


def test_has_scenarios(pack):
    \"\"\"The pack contains at least one scenario.\"\"\"
    assert len(pack.scenarios) >= 1


def test_no_duplicate_ids(pack):
    \"\"\"All scenario IDs are unique.\"\"\"
    ids = [s.id for s in pack.scenarios]
    assert len(ids) == len(set(ids))


def test_all_scenarios_have_input(pack):
    \"\"\"Every scenario has a non-empty input field.\"\"\"
    for s in pack.scenarios:
        assert s.input, f"Scenario {s.id} is missing input"
"""


@click.command()
@click.argument("path", default=".")
@click.option(
    "--template",
    type=click.Choice(["minimal", "full"]),
    default="minimal",
    help="Scaffold template to use: minimal (scenarios only) or full (agents + tests).",
)
@click.option(
    "--force",
    is_flag=True,
    help="Overwrite existing files without prompting.",
)
def init_cmd(path: str, template: str, force: bool) -> None:
    """Initialize a new EvalForge project in PATH.

    Creates the directory structure and starter files for running
    evaluation scenarios.  The ``minimal`` template gives you a config
    file and a single example scenario pack; the ``full`` template adds
    an agent stub, a test file, and fixture scaffolding.

    Args:
        path: Target directory for the new project (default: current dir).
        template: Scaffold template (minimal or full).
        force: Overwrite existing files without prompting.

    Exits with:
        0 on success (files may be skipped if they already exist without
        --force).
    """
    root = Path(path).resolve()

    # ---------------------------------------------------------------
    # Files that both templates share
    # ---------------------------------------------------------------
    files: dict[str, str] = {
        "evalforge.toml": _TEMPLATE_EVALFORGE_TOML,
        "scenarios/my-scenarios.yaml": _TEMPLATE_SCENARIO_PACK,
    }

    # ---------------------------------------------------------------
    # Full template extras
    # ---------------------------------------------------------------
    if template == "full":
        files.update({
            "agents/my_agent.py": _TEMPLATE_AGENT,
            "tests/test_scenarios.py": _TEMPLATE_TEST_SCENARIOS,
        })

    # ---------------------------------------------------------------
    # Write files
    # ---------------------------------------------------------------
    created: list[str] = []
    overwritten: list[str] = []
    skipped: list[str] = []

    for rel_path, content in files.items():
        dest = root / rel_path
        dest.parent.mkdir(parents=True, exist_ok=True)

        if dest.exists() and not force:
            skipped.append(rel_path)
            continue

        was_overwrite = dest.exists()
        dest.write_text(content, encoding="utf-8")
        if was_overwrite:
            overwritten.append(rel_path)
        else:
            created.append(rel_path)

    # Ensure empty directories for full template
    if template == "full":
        (root / "fixtures").mkdir(parents=True, exist_ok=True)

    # ---------------------------------------------------------------
    # Report
    # ---------------------------------------------------------------
    _print_report(root, template, created, overwritten, skipped)

    if skipped:
        click.echo(
            "\n[dim]Tip: run with --force to overwrite existing files.[/dim]"
        )


def _print_report(
    root: Path,
    template: str,
    created: list[str],
    overwritten: list[str],
    skipped: list[str],
) -> None:
    """Print a Rich-styled summary of what was created / skipped.

    Uses Rich's Panel component to render a formatted report showing
    created files (green), overwritten files (yellow), and skipped
    files (dim).

    Args:
        root: Root directory of the scaffolded project.
        template: Template name ("minimal" or "full").
        created: List of relative paths for newly created files.
        overwritten: List of relative paths for overwritten files.
        skipped: List of relative paths for files that already exist.
    """
    from rich.console import Console
    from rich.panel import Panel
    from rich.text import Text

    console = Console()
    lines: list[Text] = []

    label_template = template.capitalize()
    lines.append(Text(f"Template: {label_template}", style="bold cyan"))
    lines.append(Text(f"Root:     {root}"))

    if created:
        lines.append(Text(""))
        lines.append(Text("Created:", style="bold green"))
        for f in created:
            lines.append(Text(f"  + {f}", style="green"))

    if overwritten:
        lines.append(Text(""))
        lines.append(Text("Overwritten:", style="bold yellow"))
        for f in overwritten:
            lines.append(Text(f"  ~ {f}", style="yellow"))

    if skipped:
        lines.append(Text(""))
        lines.append(Text("Skipped (already exist):", style="bold dim"))
        for f in skipped:
            lines.append(Text(f"  \u2022 {f}", style="dim"))

    panel = Panel(
        Text.assemble(*lines) if len(lines) > 1 else lines[0],
        title="EvalForge Init",
        border_style="cyan",
    )
    console.print(panel)
